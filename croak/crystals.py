r"""Type I (oo→e) second-harmonic generation in a uniaxial crystal.

The forward model (:mod:`croak.forward`, :mod:`croak.forward_jax`) integrates the
signal generated at every depth :math:`z` of the medium and propagates it to the
exit face. For PG and SD the fundamental and the signal share one propagation
constant. For SHG they do not: the signal lives near :math:`2\omega_0`, and in a
Type I crystal it is the extraordinary wave while the fundamentals are ordinary.
This module supplies the two propagation constants and the generation prefactor.

Propagation constants
---------------------
Both are written on the model's centred grid :math:`\Omega` (relative to the pulse
carrier :math:`\omega_0` for the fundamental, and to :math:`2\omega_0` for the
signal) and in **one** frame moving with the fundamental's group velocity
:math:`\beta_1 = \mathrm d k_z/\mathrm d\omega|_{\omega_0}`:

.. math::

    \beta_\mathrm{in}(\Omega)  &= k_z(\omega_0+\Omega) - \beta_1\Omega, \qquad
    k_z(\omega) = \sqrt{k_o(\omega)^2 - (\omega\sin\alpha/c)^2}, \\
    \beta_\mathrm{sig}(\Omega) &= k_s(2\omega_0+\Omega) - \beta_1\Omega, \qquad
    k_s(\omega) = \frac{\omega}{c}\, n_e(\theta, \omega).

:math:`k_o = \omega n_o/c` is the ordinary wavevector. :math:`k_z` is its
component along the bisector of two beams crossing at the external half-angle
:math:`\alpha` (:class:`~croak.geometry.TwoBeamGeometry`): the transverse
wavevector :math:`\omega\sin\alpha/c` is conserved across the entrance face, and
the ordinary index does not depend on direction, so no refraction step is needed.
:math:`n_e(\theta,\omega)` is the extraordinary index of a wave at the internal
angle :math:`\theta` to the optic axis,
:math:`1/n_e(\theta)^2 = \cos^2\theta/n_o^2 + \sin^2\theta/n_e^2`.

The carrier wavevectors are kept. A component pair :math:`(\omega_1, \omega_2)`
generated at depth :math:`z` and propagated to the exit then carries
:math:`\exp(-i\Delta k\, z)` with the exact mismatch

.. math:: \Delta k = k_s(\omega_1+\omega_2) - k_z(\omega_1) - k_z(\omega_2),

because the frame terms cancel: :math:`-\beta_1(\Omega_1+\Omega_2)z
-\beta_1\Omega_s(L-z) = -\beta_1\Omega_s L` does not depend on :math:`z`, and only
adds a linear spectral phase, which the trace :math:`|\psi|^2` cannot see. The depth
sum therefore produces the phase-matching response,
:math:`\mathrm{sinc}(\Delta k L/2)` per pair, by itself.

Generation prefactor
--------------------
The second-harmonic field generated by a polarisation :math:`P` grows as
:math:`i\omega_s P/(2 n_s c)` (slowly varying envelope). The model multiplies the
signal by :math:`(\omega_s/n_s)/(2\omega_0/n_s(2\omega_0))`, normalised at the
carrier. Other spectral factors (the beams' mode overlap, the dispersion of
:math:`\chi^{(2)}`, the detector) are left to the solvers' ``R_omega``.

Crystal angle
-------------
The manufacturer specifies the cut angle :math:`\theta_c` between the optic axis
and the face normal. A crystal tilted by the external angle :math:`\gamma` (in the
principal plane; positive increases the angle to the optic axis) refracts the beams
to :math:`\gamma_\mathrm{int} = \arcsin(\sin\gamma / n_o)`, so that
:math:`\theta = \theta_c + \gamma_\mathrm{int}`, and the path through a plate of
thickness :math:`L` is :math:`L/\cos\gamma_\mathrm{int}`. :class:`CrystalSetup`
takes either :math:`\gamma` or the wavelength the crystal was tuned to
phase-match, from which :math:`\theta` is solved. Approximations: the refraction
uses :math:`n_o` at one wavelength (the phase-matched one, else the carrier), and the
crossing geometry is taken at normal incidence.

Validity
--------
* Type I only, fundamentals ordinary; no walk-off (thin crystal, full collection).
* The signal of a pair :math:`(\omega_1,\omega_2)` leaves at a small angle
  :math:`\delta\theta \approx (\omega_1-\omega_2)\sin\alpha/(\omega_s n_s)` to the
  bisector, which the model neglects. When the beams cross in the crystal's
  principal plane (fundamental polarisation perpendicular to the crossing plane),
  that tilt changes :math:`n_e(\theta)` to first order;
  :func:`tilt_phase_error` estimates the phase it adds and the forward models warn
  above :data:`TILT_PHASE_WARN`. When the polarisation lies in the crossing plane,
  the principal plane is perpendicular to it and the first-order term vanishes.

See :doc:`/explanation/forward_model` for the full model.
"""

